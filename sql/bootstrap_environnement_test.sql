-- Découverte en générant ce script : 13 tables de prod n'ont JAMAIS eu de
-- ALTER TABLE ... ENABLE ROW LEVEL SECURITY explicite dans AUCUN fichier
-- sql/*.sql (mail_check_lock, campagnes, utilisateur_campagnes,
-- mail_check_runs, contracts, remboursements, email_events,
-- leads_professionnels, registre_suppressions_rgpd, emails_blacklistes,
-- intake_responses, utilisateurs_dashboard, agence_config) — pourtant
-- confirmées RLS-actives en prod par scripts/controle_sante_bdd.py
-- (contrôle couverture_rls, statut "ok", 31/31 tables). Explication la
-- plus probable : c'est précisément le rôle de l'event trigger
-- rls_auto_enable() ci-dessus (non reconstruit ici) — ces tables datent
-- d'après sa mise en place et n'ont donc jamais eu besoin d'un ALTER
-- explicite écrit à la main.
--
-- Sans ce même event trigger actif sur le projet test, ces 13 tables
-- resteraient PUBLIQUEMENT lisibles/écrivables via la clé anon — exposition
-- que ce projet a déjà classée "URGENT" une fois en prod (voir
-- sql/fix_rls_ceo_reports.sql). D'où ce filet de sécurité explicite,
-- exhaustif sur les 32 tables de ce script, qui ne dépend d'aucun event
-- trigger : IF EXISTS + répétition sans risque des ALTER déjà exécutés
-- plus haut pour les 19 autres tables.

DO $$
DECLARE
    t TEXT;
BEGIN
    FOREACH t IN ARRAY ARRAY[
        'agence_config', 'agent_memories', 'articles', 'artisans', 'campagnes',
        'ceo_reports', 'contracts', 'couts_infrastructure', 'demandes_devis_particuliers',
        'echeances', 'email_events', 'emails_blacklistes', 'error_log', 'intake_responses',
        'journal_audit_admin', 'kpis', 'leads', 'leads_professionnels', 'mail_check_lock',
        'mail_check_runs', 'migrations_appliquees', 'propositions_expirees', 'reclamations',
        'registre_suppressions_rgpd', 'remboursements', 'sante_base_donnees',
        'satisfaction_enquetes', 'stripe_webhook_events', 'tasks', 'utilisateur_campagnes',
        'utilisateur_leads', 'utilisateurs_dashboard'
    ]
    LOOP
        IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = t) THEN
            EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
        END IF;
    END LOOP;
END $$;
